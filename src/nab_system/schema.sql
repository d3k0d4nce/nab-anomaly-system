-- NAB Anomaly Detection System — PostgreSQL schema (11 tables)
-- Types follow the system passport. A few audit fields are added without
-- changing the logical model.

CREATE TABLE IF NOT EXISTS time_series (
    series_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            TEXT NOT NULL UNIQUE,
    source          TEXT NOT NULL,
    category        TEXT,
    criticality     SMALLINT NOT NULL DEFAULT 3 CHECK (criticality BETWEEN 1 AND 5),
    step_seconds    INTEGER NOT NULL CHECK (step_seconds > 0),
    description     TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS observations (
    observation_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id       BIGINT NOT NULL REFERENCES time_series(series_id) ON DELETE CASCADE,
    ts              TIMESTAMPTZ NOT NULL,
    value           DOUBLE PRECISION,
    is_imputed      BOOLEAN NOT NULL DEFAULT FALSE,
    split           TEXT NOT NULL DEFAULT 'unknown'
                    CHECK (split IN ('train', 'validation', 'test', 'unknown')),
    UNIQUE (series_id, ts)
);
CREATE INDEX IF NOT EXISTS observations_series_ts_idx
    ON observations(series_id, ts);

CREATE TABLE IF NOT EXISTS detection_params (
    params_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id           BIGINT NOT NULL REFERENCES time_series(series_id) ON DELETE CASCADE,
    anomaly_threshold   DOUBLE PRECISION,          -- calibrated p for WARNING
    critical_threshold  DOUBLE PRECISION,          -- calibrated p for INCIDENT
    evidence_warning    DOUBLE PRECISION,          -- operational evidence threshold
    evidence_incident   DOUBLE PRECISION,
    k_consecutive       INTEGER NOT NULL DEFAULT 2,
    min_history         INTEGER NOT NULL DEFAULT 576,
    window_size         INTEGER NOT NULL DEFAULT 288,
    end_after           INTEGER NOT NULL DEFAULT 48,
    exit_ratio          DOUBLE PRECISION NOT NULL DEFAULT 0.60,
    valid_from          TIMESTAMPTZ NOT NULL DEFAULT now(),
    version             TEXT NOT NULL DEFAULT 'v1',
    UNIQUE (series_id, version)
);

CREATE TABLE IF NOT EXISTS deviation_episodes (
    episode_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id       BIGINT NOT NULL REFERENCES time_series(series_id) ON DELETE CASCADE,
    started_at      TIMESTAMPTZ NOT NULL,
    ended_at        TIMESTAMPTZ,
    peak_evidence   DOUBLE PRECISION,
    warning_sent    BOOLEAN NOT NULL DEFAULT FALSE,
    incident_sent   BOOLEAN NOT NULL DEFAULT FALSE,
    repeat_alerts   INTEGER NOT NULL DEFAULT 0,
    final_action    TEXT CHECK (final_action IN ('WARNING', 'INCIDENT')),
    UNIQUE (series_id, started_at)
);
CREATE INDEX IF NOT EXISTS deviation_episodes_series_idx
    ON deviation_episodes(series_id, started_at);

CREATE TABLE IF NOT EXISTS duty_engineers (
    engineer_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       TEXT NOT NULL UNIQUE,
    contact         TEXT,
    login           TEXT UNIQUE,
    password_hash   TEXT,
    role            TEXT NOT NULL DEFAULT 'operator'
                    CHECK (role IN ('operator', 'admin')),
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    is_on_duty      BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS decisions (
    decision_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    observation_id  BIGINT NOT NULL UNIQUE REFERENCES observations(observation_id) ON DELETE CASCADE,
    params_id       BIGINT REFERENCES detection_params(params_id),
    episode_id      BIGINT REFERENCES deviation_episodes(episode_id) ON DELETE SET NULL,
    anomaly_score   DOUBLE PRECISION,              -- calibrated probability p
    evidence        DOUBLE PRECISION,              -- -log10 tail probability
    action          TEXT NOT NULL CHECK (action IN ('SKIP', 'WARNING', 'INCIDENT')),
    reason          TEXT,
    latency_ms      INTEGER NOT NULL DEFAULT 0,
    decided_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS decisions_action_idx ON decisions(action);

CREATE TABLE IF NOT EXISTS alerts (
    alert_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    decision_id         BIGINT NOT NULL UNIQUE REFERENCES decisions(decision_id) ON DELETE CASCADE,
    engineer_id         BIGINT REFERENCES duty_engineers(engineer_id),
    alert_type          TEXT NOT NULL CHECK (alert_type IN ('WARNING', 'INCIDENT')),
    status              TEXT NOT NULL DEFAULT 'OPEN'
                        CHECK (status IN ('OPEN', 'ACKNOWLEDGED', 'CLOSED')),
    deviation_kind      TEXT,
    response_limit_min  INTEGER NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS alerts_status_idx ON alerts(status, created_at);

CREATE TABLE IF NOT EXISTS check_results (
    check_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id        BIGINT NOT NULL UNIQUE REFERENCES alerts(alert_id) ON DELETE CASCADE,
    engineer_id     BIGINT NOT NULL REFERENCES duty_engineers(engineer_id),
    is_real_fault   BOOLEAN,
    verdict         TEXT,
    comment         TEXT,
    started_at      TIMESTAMPTZ,
    finished_at     TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS log_entries (
    log_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    observation_id  BIGINT REFERENCES observations(observation_id) ON DELETE CASCADE,
    alert_id        BIGINT REFERENCES alerts(alert_id) ON DELETE SET NULL,
    entry_type      TEXT NOT NULL,
    message         TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS log_entries_observation_idx
    ON log_entries(observation_id);

CREATE TABLE IF NOT EXISTS quality_stats (
    stats_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id       BIGINT REFERENCES time_series(series_id) ON DELETE CASCADE,
    params_id       BIGINT REFERENCES detection_params(params_id) ON DELETE SET NULL,
    split           TEXT NOT NULL,
    method          TEXT NOT NULL,
    tp              INTEGER NOT NULL DEFAULT 0,
    fp              INTEGER NOT NULL DEFAULT 0,
    fn              INTEGER NOT NULL DEFAULT 0,
    tn              INTEGER NOT NULL DEFAULT 0,
    tp_warning      INTEGER NOT NULL DEFAULT 0,
    tp_incident     INTEGER NOT NULL DEFAULT 0,
    fp_warning      INTEGER NOT NULL DEFAULT 0,
    fp_incident     INTEGER NOT NULL DEFAULT 0,
    recall          NUMERIC(6, 4),
    precision       NUMERIC(6, 4),
    f1              NUMERIC(6, 4),
    fp_per_24h      NUMERIC(8, 4),
    p95_latency_ms  INTEGER,
    cost_units      NUMERIC(10, 2),
    computed_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS quality_stats_series_idx
    ON quality_stats(series_id, method, split);

CREATE TABLE IF NOT EXISTS label_windows (
    window_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id       BIGINT NOT NULL REFERENCES time_series(series_id) ON DELETE CASCADE,
    start_ts        TIMESTAMPTZ NOT NULL,
    end_ts          TIMESTAMPTZ NOT NULL,
    onset_ts        TIMESTAMPTZ,
    source          TEXT NOT NULL DEFAULT 'NAB',
    is_test         BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (series_id, start_ts, end_ts)
);
CREATE INDEX IF NOT EXISTS label_windows_series_idx
    ON label_windows(series_id, start_ts);
